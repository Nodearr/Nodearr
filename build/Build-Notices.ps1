#requires -Version 7
<#
.SYNOPSIS
    Writes THIRD-PARTY-NOTICES.md: everything other people wrote that a Nodearr release carries,
    with each licence's text.

.DESCRIPTION
    Three parts, each from what is really built and shipped:

    - The transport sidecar's Rust crates, for every target it is built for, from cargo-about.
    - The NuGet packages of the projects a release publishes.
    - The npm packages webpack put in the web UI, read from the UI's source maps.

    The self-contained packages also carry the .NET runtime. Its own licence and notices are
    copied into each package by Build-Release.ps1, from the SDK that built it.

    Run it again whenever a dependency changes, and commit the result. It needs cargo-about
    (cargo install cargo-about --locked --features cli), a restore of the solution, and the web
    UI built with yarn build --env production.

.PARAMETER UiFolder
    The built web UI. The default is _output/UI.

.PARAMETER Output
    The default is THIRD-PARTY-NOTICES.md in the repository.
#>
[CmdletBinding()]
param(
    [string] $UiFolder,
    [string] $Output
)

$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$UiFolder = $UiFolder ? $UiFolder : (Join-Path $repo '_output/UI')
$Output = $Output ? $Output : (Join-Path $repo 'THIRD-PARTY-NOTICES.md')
$notices = Join-Path $PSScriptRoot 'notices'
$temp = New-Item -ItemType Directory -Force (Join-Path ([IO.Path]::GetTempPath()) 'nodearr-notices')

if (-not (Get-Command cargo-about -ErrorAction SilentlyContinue)) { throw 'cargo-about is missing: cargo install cargo-about --locked --features cli' }
if (-not (Get-ChildItem $UiFolder -Filter '*.js.map' -ErrorAction SilentlyContinue)) { throw "No source maps in $UiFolder. Build the UI first: yarn build --env production" }

# The licence texts for packages that name a licence and carry no file of their own, as SPDX
# publishes them (https://github.com/spdx/license-list-data).
function Get-LicenceText([string] $id) {
    $file = Join-Path $notices "licenses/$id.txt"

    return (Test-Path $file) ? (Get-Content $file -Raw).TrimEnd() : $null
}

function Format-Text([string] $text) {
    # A fence that the text itself cannot close.
    return "``````text`n$($text.TrimEnd())`n``````"
}

# Licences that older packages give only as the address of a licence's page.
$LicenceUrls = @{
    'http://www.apache.org/licenses/LICENSE-2.0' = 'Apache-2.0'
    'https://www.apache.org/licenses/LICENSE-2.0' = 'Apache-2.0'
    'http://opensource.org/licenses/MIT' = 'MIT'
    'https://opensource.org/licenses/MIT' = 'MIT'
}

$parts = [System.Collections.Generic.List[string]]::new()

$parts.Add(@'
# Third-party notices

Nodearr is free software under the GNU General Public License v3.0 (`LICENSE`). Most of it is derived from Sonarr and Prowlarr (`NOTICE.md`). A release also carries the work of the people and projects below, under their own licences, whose texts are given here as those licences ask.

This file is generated by `build/Build-Notices.ps1` from what a release is built from. Do not edit it by hand.

The self-contained packages also carry the .NET runtime, which is under the MIT licence with notices of its own. Those are in each package as `dotnet-LICENSE.txt` and `dotnet-THIRD-PARTY-NOTICES.txt`. The Docker image is built on Microsoft's `aspnet` image, which carries them itself.

Source code: Nodearr publishes everything here unmodified, and its source is where each entry links to. That is where the source of the packages under the Mozilla Public License 2.0 (`attohttpc` in the sidecar, `IPAddressRange` in the application) is available, as section 3.2 of that licence asks. `ffprobe` is under the GNU Lesser General Public License, and its entry says where its corresponding source is.
'@)

# --- The transport sidecar ---------------------------------------------------------------------

Write-Host 'Reading the sidecar''s crates'
$rust = Join-Path $temp 'rust.md'
Push-Location (Join-Path $repo 'transport')
try {
    cargo about generate -c (Join-Path $notices 'about.toml') -o $rust --locked (Join-Path $notices 'cargo-about.hbs') 2>$null
    if ($LASTEXITCODE -ne 0) { throw 'cargo-about failed. Run it by hand in transport/ to see why.' }
}
finally {
    Pop-Location
}

$parts.Add((Get-Content $rust -Raw).TrimEnd())

# --- NuGet packages ----------------------------------------------------------------------------

Write-Host 'Reading the NuGet packages'
$projects = @(
    'src/NzbDrone.Console/Nodearr.Console.csproj',
    'src/NzbDrone/Nodearr.csproj',
    'src/NzbDrone.Update/Nodearr.Update.csproj',
    'src/ServiceHelpers/ServiceInstall/ServiceInstall.csproj',
    'src/ServiceHelpers/ServiceUninstall/ServiceUninstall.csproj'
)

$packages = @{}

foreach ($project in $projects) {
    $json = dotnet list (Join-Path $repo $project) package --include-transitive --format json 2>$null | ConvertFrom-Json

    foreach ($framework in $json.projects.frameworks) {
        foreach ($package in @($framework.topLevelPackages) + @($framework.transitivePackages)) {
            if ($package) { $packages["$($package.id)/$($package.resolvedVersion)"] = $package }
        }
    }
}

$globalPackages = ((dotnet nuget locals global-packages --list) -replace '^global-packages:\s*', '').Trim()
$nuget = [System.Collections.Generic.List[string]]::new()
$nugetTexts = [ordered]@{}

$nuget.Add(@'
## The .NET application

The NuGet packages the application, the tray app, the updater and the service helpers are built with. A licence given as a name has its text at the end of this part, and one given as a file has its own text under the package.
'@)

foreach ($key in ($packages.Keys | Sort-Object)) {
    $package = $packages[$key]
    $id = $package.id
    $version = $package.resolvedVersion
    $folder = Join-Path $globalPackages "$($id.ToLowerInvariant())/$($version.ToLowerInvariant())"
    $nuspecFile = Join-Path $folder "$($id.ToLowerInvariant()).nuspec"

    if (-not (Test-Path $nuspecFile)) { throw "No nuspec for $id $version at $nuspecFile. Restore the solution first." }

    [xml] $nuspec = Get-Content $nuspecFile -Raw
    $metadata = $nuspec.package.metadata
    $licence = $metadata.license
    $url = $metadata.projectUrl ? $metadata.projectUrl : "https://www.nuget.org/packages/$id/$version"
    $copyright = $metadata.copyright ? $metadata.copyright : $metadata.authors

    $entry = "### [$id $version]($url)`n`n"
    $entry += $copyright ? "$copyright`n`n" : ''

    if ($licence -and $licence.type -eq 'expression') {
        $expression = $licence.'#text'
        $entry += "Licence: $expression"

        foreach ($spdx in ($expression -split '\s+(?:OR|AND|WITH)\s+' | ForEach-Object { $_.Trim('(', ')', ' ') })) {
            if (-not (Get-LicenceText $spdx)) { throw "No text for the licence $spdx, used by $id. Add build/notices/licenses/$spdx.txt from SPDX." }
            $nugetTexts[$spdx] = $true
        }
    }
    elseif ($licence -and $licence.type -eq 'file') {
        $entry += "Licence:`n`n$(Format-Text (Get-Content (Join-Path $folder $licence.'#text') -Raw))"
    }
    elseif ($metadata.licenseUrl -and $LicenceUrls.ContainsKey($metadata.licenseUrl.TrimEnd('/'))) {
        # Older packages point at a licence's page instead of naming it.
        $spdx = $LicenceUrls[$metadata.licenseUrl.TrimEnd('/')]
        $entry += "Licence: $spdx, given as $($metadata.licenseUrl)"
        $nugetTexts[$spdx] = $true
    }
    else {
        # What the package says about itself, kept here, for a package that names no licence.
        $known = Join-Path $notices "nuget/$($id.ToLowerInvariant()).txt"

        if (-not (Test-Path $known)) { throw "$id $version names no licence. Find out what it is under and write it in build/notices/nuget/$($id.ToLowerInvariant()).txt." }

        $entry += (Get-Content $known -Raw).TrimEnd()

        foreach ($spdx in [regex]::Matches((Get-Content $known -Raw), 'The ([A-Za-z0-9.+-]+) licence"') | ForEach-Object { $_.Groups[1].Value }) {
            $nugetTexts[$spdx] = $true
        }
    }

    $nuget.Add($entry)
}

foreach ($spdx in $nugetTexts.Keys) {
    $nuget.Add("### The $spdx licence`n`n$(Format-Text (Get-LicenceText $spdx))")
}

$parts.Add($nuget -join "`n`n")

# --- npm packages in the web UI ----------------------------------------------------------------

Write-Host 'Reading the web UI''s packages'
$packageDirs = [System.Collections.Generic.SortedSet[string]]::new()

foreach ($map in Get-ChildItem $UiFolder -Filter '*.js.map') {
    foreach ($source in (Get-Content $map.FullName -Raw | ConvertFrom-Json).sources) {
        # webpack://nodearr/./node_modules/a/node_modules/@scope/b/lib/x.js -> node_modules/a/node_modules/@scope/b
        if ($source -match '^(?:.*?/)?((?:node_modules/(?:@[^/]+/)?[^/]+/)*node_modules/(?:@[^/]+/)?[^/]+)/') {
            [void] $packageDirs.Add($Matches[1])
        }
    }
}

$npm = [System.Collections.Generic.List[string]]::new()
$npmTexts = [ordered]@{}

$npm.Add(@'
## The web UI

The npm packages webpack put in the web UI. Each one's own licence file follows it. One that has none has its licence's text at the end of this part.
'@)

foreach ($dir in $packageDirs) {
    $path = Join-Path $repo $dir
    $manifest = Get-Content (Join-Path $path 'package.json') -Raw | ConvertFrom-Json
    $licence = $manifest.license ? $manifest.license : ($manifest.licenses ? ($manifest.licenses | ForEach-Object { $_.type }) -join ' OR ' : $null)
    $repository = $manifest.repository ? ($manifest.repository -is [string] ? $manifest.repository : $manifest.repository.url) : $null
    $url = $repository ? ($repository -replace '^git\+', '' -replace '\.git$', '' -replace '^git://', 'https://' -replace '^github:', 'https://github.com/') : "https://www.npmjs.com/package/$($manifest.name)"

    if ($url -notmatch '^https?://') { $url = "https://www.npmjs.com/package/$($manifest.name)" }

    $entry = "### [$($manifest.name) $($manifest.version)]($url)`n`nLicence: $licence"
    $file = Get-ChildItem $path -File | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING)(\.|-|$)' } | Select-Object -First 1

    if ($file) {
        $entry += "`n`n$(Format-Text (Get-Content $file.FullName -Raw))"
    }
    else {
        if (-not $licence) { throw "$($manifest.name) says nothing about its licence." }

        foreach ($spdx in ($licence -split '\s+(?:OR|AND|WITH)\s+' | ForEach-Object { $_.Trim('(', ')', ' ') })) {
            if (-not (Get-LicenceText $spdx)) { throw "No text for the licence $spdx, used by $($manifest.name). Add build/notices/licenses/$spdx.txt from SPDX." }
            $npmTexts[$spdx] = $true
        }

        $author = $manifest.author ? ($manifest.author -is [string] ? $manifest.author : $manifest.author.name) : $null
        $entry += $author ? "`n`nBy $author." : ''
    }

    $npm.Add($entry)
}

foreach ($spdx in $npmTexts.Keys) {
    $npm.Add("### The $spdx licence`n`n$(Format-Text (Get-LicenceText $spdx))")
}

$parts.Add($npm -join "`n`n")

# Unix line endings everywhere, so the file is the same whichever machine wrote it.
($parts -join "`n`n").Replace("`r`n", "`n") + "`n" | Set-Content $Output -NoNewline -Encoding utf8NoBOM

Write-Host "Wrote ${Output}: $($packages.Count) NuGet packages, $($packageDirs.Count) npm packages"
